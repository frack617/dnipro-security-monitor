def concise(text):
    for _ in range(2):
        for pattern,replacement in RULES:
            text=re.sub(pattern,replacement,text)
    text=text.replace('Поранені Троє', 'Поранені троє')
    text=text.replace('у Синельникове зросла', 'у Синельниковому зросла')
    return text


def clinical_overlap(records):
    """Bounded same-episode clause proofs, never whole-post suppression.

    Require one detailed police shop attack, the same specific community,
    day, weapon, four patients, and the same child's age. A second candidate
    or repeated-attack marker disables consolidation. Unknown clauses stay.
    Each proof lists exact target clauses; the publication gate checks that
    their projections still appear in the correct public paragraph.
    """
    from datetime import datetime
    from zoneinfo import ZoneInfo
    from fallback_report import sentences
    candidates=[]
    for r in records:
        raw=r['source_text']
        if (r['source_key'].split('/')[0].casefold()=='gunpvdp' and
            not r.get('reporting_period') and r.get('display') and
            re.search(r'по продуктовому магазину на Нікопольщині: четверо поранених, серед них дитина',raw) and
            re.search(r'Покровської міської територіальної громади',raw) and
            re.search(r'троє чоловіків віком від \d+ до \d+ років',raw)):
            age=re.search(r'тяжких травм зазнав (\d+)-річний хлопчик',raw)
            if age:candidates.append((r,age[1]))
    proofs=[]
    for police,age in candidates:
        day=datetime.fromisoformat(police['published_at']).astimezone(ZoneInfo('Europe/Kyiv')).date()
        same=[r for r in records if r['source_key'].split('/')[0].casefold()=='dnipropetrovskaoda'
              and not r.get('reporting_period') and r.get('display')
              and datetime.fromisoformat(r['published_at']).astimezone(ZoneInfo('Europe/Kyiv')).date()==day
              and 'Покровську громаду Нікопольщини' in r['source_text']
              and f'{age}-річного хлопчика' in r['source_text']
              and 'Четверо людей дістали поранень через атаку ворожого безпілотника' in r['source_text']]
        if len(same)!=1 or len(candidates)!=1:continue
        ova=same[0]
        if re.search(r'знову|повторн|ще одн\w* атак',ova['source_text']+police['source_text'],re.I):continue
        pu=[c['source_text'] for c in police.get('claims',[]) if c['disposition']=='required']
        ou=[c['source_text'] for c in ova.get('claims',[]) if c['disposition']=='required']
        heading=next((s for s in pu if s.startswith('Армія рф вдарила БпЛА по продуктовому магазину')),None)
        community=next((s for s in pu if 'Покровської міської територіальної громади' in s),None)
        adults=next((s for s in pu if s.startswith('Також постраждали троє чоловіків віком')),None)
        hospital=next((s for s in ou if s.startswith(age+'-річного хлопчика доправили')),None)
        severe=next((s for s in ou if s=='Його стан медики оцінюють як тяжкий.'),None)
        if not all((heading,community,adults,hospital,severe)):continue
        for s in ou:
            if s.startswith('Четверо людей дістали поранень через атаку ворожого безпілотника'):
                proofs.append((ova, s, [heading,community]))
            if s=='Постраждали троє дорослих і дитина.':
                proofs.append((ova,s,[heading,adults]))
        for s in pu:
            if s.startswith('Унаслідок атаки тяжких травм зазнав '+age+'-річний хлопчик'):
                proofs.append((police,s,[hospital,severe]))
    return proofs
