def formula(text):
    return any(re.fullmatch(p, text.strip(), re.I) for p in FORMULAS)


def selection_lines(text):
    # Telegram splits inline UI labels across lines. Join only a recognised
    # form sequence so its full sentence can be checked, not a fuzzy prefix.
    from fallback_report import clean_lines
    lines = [(line.strip() if line.strip() in {'App Store','Google Play'} else clean_lines(line)).strip(' ▫️📲➡️📍☎️🚰🚱‼️🤝❗') for line in text.splitlines()]
    lines = [line for line in lines if line]
    result=[];i=0
    sequences = [r'У вкладці «Сервіси» обрати графу «Соціальні послуги» та натиснути кнопку «Пошкоджене майно»\.',
                 r'Завантажити застосунок можна у App Store та Google Play',
                 r'Мапа територій, які потрапляють під відключення\.']
    while i<len(lines):
        found=False
        for width in range(1,min(6,len(lines)-i)+1):
            joined=' '.join(lines[i:i+width])
            if any(re.fullmatch(p,joined,re.I) for p in sequences):
                i+=width;found=True;break
        if found:continue
        # A known municipal contact footer is removed only as an exact pair.
        if (i+2<len(lines) and re.fullmatch(r'Адміністрація Шевченківського району:',lines[i])
            and lines[i+1]=='вул. Михайла Грушевського, 70'
            and re.fullmatch(r'Телефон для довідок:\s*093-606-95-85',lines[i+2])):
            i+=3;continue
        result.append(re.sub(r'^:\s+(?=[Уу]\s)', '', lines[i]));i+=1
    return result
